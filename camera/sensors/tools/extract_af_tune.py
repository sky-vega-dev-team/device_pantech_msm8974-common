"""
Take the auto focus tuning of one actuator out of a stock Pantech
libmmcamera2_sensor_modules.so and print it as C in the layout of the
hammerhead module, for actuator/af_tune_shim.c.

Both modules build in a table of af_tune_parms_t, two rows of one entry for
each actuator camera name, which the kernel reports as the cell-index of the
actuator. The Pantech entries are 1860 bytes: they have 16 more bytes at 216
and at 268 than the 1828 byte hammerhead ones, and the same fields
otherwise (the actuator part, at 584 in the hammerhead layout, reads 32 bytes
further on in the Pantech module).

usage: extract_af_tune.py <libmmcamera2_sensor_modules.so> <device> <cell-index>
"""

import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from extract_sensor_lib import Elf  # noqa: E402

VERSION = 0x301
PT_ENTRY = 1860
PT_ENTRIES = 6
ROWS = 2
PT_EXTRA = ((216, 16), (268, 16))
HH_ENTRY = PT_ENTRY - sum(n for _, n in PT_EXTRA)


def find_table(e):
    """Address of the table: entries of VERSION with names 0 to 5, twice."""
    v, o, fs, ms = e.segs[-1]
    data = e.read(v, fs)
    size = ROWS * PT_ENTRIES * PT_ENTRY
    for off in range(0, len(data) - size + 1, 4):
        if all(struct.unpack_from('<II', data, off + i * PT_ENTRY) == (VERSION, i % PT_ENTRIES)
               for i in range(ROWS * PT_ENTRIES)):
            return v + off
    raise SystemExit('no actuator table found')


def to_hammerhead(entry):
    out, pos = b'', 0
    for at, n in PT_EXTRA:
        out += entry[pos:at]
        pos = at + n
    return out + entry[pos:]


def main():
    lib, device, cam = sys.argv[1], sys.argv[2], int(sys.argv[3])
    e = Elf(lib)
    base = find_table(e)
    rows = [to_hammerhead(e.read(base + (r * PT_ENTRIES + cam) * PT_ENTRY, PT_ENTRY))
            for r in range(ROWS)]
    assert all(len(r) == HH_ENTRY for r in rows)

    print('/*')
    print(' * Generated by tools/extract_af_tune.py from the stock')
    print(' * libmmcamera2_sensor_modules.so of the Pantech %s: the tuning of' % device)
    print(' * actuator camera name %d, in the hammerhead layout. Do not edit.' % cam)
    print(' */')
    print()
    print('#include "af_tune.h"')
    print()
    print('const uint32_t pantech_af_tune_cam = %d;' % cam)
    print()
    print('const uint8_t pantech_af_tune[AF_TUNE_ROWS][AF_TUNE_SIZE] = {')
    for r in rows:
        print('    {')
        for i in range(0, len(r), 16):
            print('        ' + ' '.join('0x%02x,' % b for b in r[i:i + 16]))
        print('    },')
    print('};')


if __name__ == '__main__':
    main()
